import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// The web app reads the same root .env as the API. Values already set in the environment win.
const rootEnv = resolve(dirname(fileURLToPath(import.meta.url)), '../../.env');
if (existsSync(rootEnv)) {
  for (const line of readFileSync(rootEnv, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (!m || m[1] in process.env) continue;
    process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}

/** Where this server reaches the API. Browsers never see it. */
const apiInternal = process.env.API_INTERNAL_URL || 'http://localhost:4000';

/** @type {import('next').NextConfig} */
const nextConfig = {
  transpilePackages: ['@ticketpay/shared'],
  // Posters are local SVG files generated by the seed tooling.
  images: { dangerouslyAllowSVG: false },
  // The browser talks to the API through this app's own origin (same-origin mode). One address then
  // serves pages, the API, posters and the Midtrans notification URL: one tunnel is enough, and the
  // session cookie is always first-party, from any device.
  async rewrites() {
    return [
      { source: '/v1/:path*', destination: `${apiInternal}/v1/:path*` },
      { source: '/media/:path*', destination: `${apiInternal}/media/:path*` },
    ];
  },
  // Opening the dev server through a tunnel or another device's browser. Add LAN addresses in DEV_ALLOWED_ORIGINS.
  allowedDevOrigins: ['*.ngrok-free.app', '*.ngrok.app', '*.ngrok.io', '*.trycloudflare.com', ...(process.env.DEV_ALLOWED_ORIGINS ?? '').split(',').map((s) => s.trim()).filter(Boolean)],
};
export default nextConfig;
