import { BadRequestException, Inject, Injectable, Logger } from '@nestjs/common';
import { posterSvg } from '@ticketpay/database';
import { POSTER_MAX_BYTES } from '@ticketpay/shared';
import { randomUUID } from 'node:crypto';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ENV } from '../config/config.module';
import type { Env } from '../config/env';

/** Public path prefix of stored posters. The web app prefixes it with the API URL. */
export const POSTER_PREFIX = '/media/posters/';
export const POSTER_NAME = /^[0-9a-f-]{36}\.(png|jpg|webp|svg)$/;

/** Detects the real image type from its first bytes. The declared content type is never trusted. */
export function sniffImage(buf: Buffer): 'png' | 'jpg' | 'webp' | null {
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'png';
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'jpg';
  if (buf.length >= 12 && buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP') return 'webp';
  return null;
}

/**
 * Event posters on local disk (UPLOAD_DIR). Files get random names, so an upload can never overwrite
 * another file or reveal anything through its name. SVG is only ever generated by us, never uploaded.
 */
@Injectable()
export class MediaService {
  private readonly log = new Logger('Media');
  readonly dir: string;

  constructor(@Inject(ENV) env: Env) {
    this.dir = join(env.UPLOAD_DIR, 'posters');
  }

  async savePoster(buf: Buffer): Promise<string> {
    if (buf.length > POSTER_MAX_BYTES) throw new BadRequestException('The poster must be 2 MB or smaller');
    const ext = sniffImage(buf);
    if (!ext) throw new BadRequestException('Upload a PNG, JPEG or WebP image');
    return this.write(`${randomUUID()}.${ext}`, buf);
  }

  /** The default poster of a new event: the category gradient with its title. */
  saveGeneratedPoster(title: string, category: string): Promise<string> {
    return this.write(`${randomUUID()}.svg`, Buffer.from(posterSvg(title, category)));
  }

  isGenerated(posterPath: string): boolean {
    return posterPath.startsWith(POSTER_PREFIX) && posterPath.endsWith('.svg');
  }

  /** Removes a stored poster that is no longer used. Seeded posters (served by the web app) are left alone. */
  async remove(posterPath: string): Promise<void> {
    if (!posterPath.startsWith(POSTER_PREFIX)) return;
    const name = posterPath.slice(POSTER_PREFIX.length);
    if (!POSTER_NAME.test(name)) return;
    await unlink(join(this.dir, name)).catch((err: NodeJS.ErrnoException) => {
      if (err.code !== 'ENOENT') this.log.warn(`Could not remove poster ${name}: ${err.message}`);
    });
  }

  private async write(name: string, buf: Buffer): Promise<string> {
    await mkdir(this.dir, { recursive: true });
    await writeFile(join(this.dir, name), buf, { flag: 'wx' });
    return `${POSTER_PREFIX}${name}`;
  }
}
